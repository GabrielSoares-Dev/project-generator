#!/bin/sh
set -u

REPO=$(cd "$(dirname "$0")/.." && pwd)
SYNC="$REPO/bin/agents-sync"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT INT TERM
PASSED=0
FAILED=0

pass() { PASSED=$((PASSED + 1)); echo "ok   $1"; }
failed() { FAILED=$((FAILED + 1)); echo "FAIL $1"; }

new_project() {
  rm -rf "$WORK/project"
  mkdir -p "$WORK/project"
  echo "$WORK/project"
}

run() {
  "$SYNC" "$@" > "$WORK/stdout" 2> "$WORK/stderr"
}

t_render_writes_both_tools() {
  p=$(new_project)
  run --project "$p" || { failed "render writes both tools: sync failed: $(cat "$WORK/stderr")"; return; }
  for f in .claude/agents/dev.md .claude/agents/qa.md .claude/agents/reviewer.md \
           .codex/agents/dev.toml .codex/agents/qa.toml .codex/agents/reviewer.toml \
           .claude/skills/tdd/SKILL.md .agents/skills/tdd/SKILL.md \
           .claude/skills/handoff-note/SKILL.md .agents/agent-team.manifest; do
    [ -f "$p/$f" ] || { failed "render writes both tools: missing $f"; return; }
  done
  pass "render writes both tools"
}

t_capabilities_map_to_permissions() {
  p=$(new_project)
  run --project "$p" || { failed "capabilities: sync failed"; return; }
  grep -q '^tools: Read, Grep, Glob' "$p/.claude/agents/reviewer.md" || { failed "capabilities: reviewer has no restricted tools"; return; }
  ! grep -q '^tools:' "$p/.claude/agents/qa.md" || { failed "capabilities: qa should inherit every tool"; return; }
  grep -qx 'sandbox_mode = "read-only"' "$p/.codex/agents/reviewer.toml" || { failed "capabilities: reviewer sandbox not read-only"; return; }
  grep -qx 'sandbox_mode = "workspace-write"' "$p/.codex/agents/dev.toml" || { failed "capabilities: dev sandbox not workspace-write"; return; }
  pass "capabilities map to each tool's permissions"
}

t_rendered_files_say_generated() {
  p=$(new_project)
  run --project "$p" || { failed "generated header: sync failed"; return; }
  grep -q 'Generated by agent-team bin/agents-sync from roles/qa.md' "$p/.claude/agents/qa.md" &&
    head -n 1 "$p/.codex/agents/qa.toml" | grep -q '^# Generated by agent-team' &&
    pass "rendered files say they are generated" ||
    failed "generated header missing"
}

t_check_passes_after_render() {
  p=$(new_project)
  run --project "$p" && run --project "$p" --check && pass "check passes right after a render" ||
    failed "check after render: $(cat "$WORK/stdout" "$WORK/stderr")"
}

t_check_fails_on_hand_edit() {
  p=$(new_project)
  run --project "$p" || { failed "hand edit: sync failed"; return; }
  echo "extra" >> "$p/.claude/agents/qa.md"
  if run --project "$p" --check; then
    failed "check should fail after a hand edit"
  else
    grep -q 'differs: .claude/agents/qa.md' "$WORK/stdout" && pass "check fails and names a hand-edited file" ||
      failed "hand edit not named: $(cat "$WORK/stdout")"
  fi
}

t_check_fails_when_never_rendered() {
  p=$(new_project)
  if run --project "$p" --check; then
    failed "check should fail when nothing was rendered"
  else
    grep -q 'missing: .claude/agents/dev.md' "$WORK/stdout" && pass "check fails when files were never rendered" ||
      failed "missing not reported"
  fi
}

t_override_is_appended() {
  p=$(new_project)
  mkdir -p "$p/agents/overrides"
  printf 'Test the three languages: pt-BR, en and es.\n' > "$p/agents/overrides/qa.md"
  run --project "$p" || { failed "override: sync failed"; return; }
  for f in .claude/agents/qa.md .codex/agents/qa.toml; do
    awk '/^## Additions for this project$/ { h = 1 } h && /three languages/ { ok = 1 } END { exit !ok }' "$p/$f" ||
      { failed "override not appended in $f"; return; }
  done
  awk '/^## Never$/ { n = NR } /^## Additions for this project$/ { a = NR } END { exit !(n && a > n) }' "$p/.claude/agents/qa.md" ||
    { failed "override must come after the role's own rules"; return; }
  pass "override is appended after the role's own rules"
}

t_new_override_makes_check_fail() {
  p=$(new_project)
  run --project "$p" || { failed "new override: sync failed"; return; }
  mkdir -p "$p/agents/overrides"
  echo "More." > "$p/agents/overrides/dev.md"
  run --project "$p" --check && failed "check should fail when an override is not rendered" ||
    pass "a new override makes the check fail until rendered"
}

t_override_for_unknown_role_fails() {
  p=$(new_project)
  mkdir -p "$p/agents/overrides"
  echo "x" > "$p/agents/overrides/ghost.md"
  run --project "$p" && failed "override for an unknown role should fail" ||
    { grep -q 'unknown role' "$WORK/stderr" && pass "an override for an unknown role fails" || failed "unknown role message"; }
}

t_project_own_skills_untouched() {
  p=$(new_project)
  mkdir -p "$p/.claude/skills/own"
  echo "mine" > "$p/.claude/skills/own/SKILL.md"
  run --project "$p" && run --project "$p" &&
    [ "$(cat "$p/.claude/skills/own/SKILL.md")" = "mine" ] &&
    run --project "$p" --check &&
    pass "the project's own skills are left alone" ||
    failed "own skill touched or check failed"
}

t_refuses_to_overwrite_unmanaged() {
  p=$(new_project)
  mkdir -p "$p/.claude/skills/tdd"
  echo "the project's own tdd" > "$p/.claude/skills/tdd/SKILL.md"
  if run --project "$p"; then
    failed "should refuse to overwrite an unmanaged file"
  else
    [ ! -f "$p/.claude/agents/dev.md" ] && [ "$(cat "$p/.claude/skills/tdd/SKILL.md")" = "the project's own tdd" ] &&
      pass "refuses to overwrite a file it does not manage, and writes nothing" ||
      failed "wrote files before refusing"
  fi
}

t_removed_role_is_cleaned_up() {
  src="$WORK/source"
  rm -rf "$src"
  cp -R "$REPO" "$src"
  p=$(new_project)
  run --project "$p" --source "$src" || { failed "removed role: first sync failed"; return; }
  rm "$src/roles/reviewer.md"
  run --project "$p" --source "$src" || { failed "removed role: second sync failed"; return; }
  [ ! -e "$p/.claude/agents/reviewer.md" ] && [ ! -e "$p/.codex/agents/reviewer.toml" ] &&
    run --project "$p" --source "$src" --check &&
    pass "a removed role's files are deleted" ||
    failed "stale files remain"
}

t_invalid_role_fails() {
  src="$WORK/source"
  rm -rf "$src"
  cp -R "$REPO" "$src"
  sed -i.bak '/^## Never$/d' "$src/roles/qa.md"
  p=$(new_project)
  run --project "$p" --source "$src" && failed "a role without ## Never should fail" ||
    { grep -q "section '## Never'" "$WORK/stderr" && pass "a role missing a section fails" || failed "section message: $(cat "$WORK/stderr")"; }
}

t_triple_quote_fails() {
  src="$WORK/source"
  rm -rf "$src"
  cp -R "$REPO" "$src"
  printf "\nUse ''' carefully.\n" >> "$src/roles/dev.md"
  p=$(new_project)
  run --project "$p" --source "$src" && failed "''' should fail" ||
    pass "text that cannot be rendered into TOML fails"
}

t_render_writes_both_tools
t_capabilities_map_to_permissions
t_rendered_files_say_generated
t_check_passes_after_render
t_check_fails_on_hand_edit
t_check_fails_when_never_rendered
t_override_is_appended
t_new_override_makes_check_fail
t_override_for_unknown_role_fails
t_project_own_skills_untouched
t_refuses_to_overwrite_unmanaged
t_removed_role_is_cleaned_up
t_invalid_role_fails
t_triple_quote_fails

echo
echo "$PASSED passed, $FAILED failed"
[ "$FAILED" -eq 0 ]
